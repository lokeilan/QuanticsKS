@testset "Cayley phase and second-order propagation" begin
    p=Problem(PeriodicGrid1D(5,8),LocalPotential1D(x->0.;id="free"),[1.])
    s=state_from_functions(p,[x->cis(2pi*x/8)];accuracy=tight)
    settings(dt,n)=TimeOptions(dt=dt,steps=n,phase_tolerance=1e-13,kinetic_tolerance=1e-14,output_tolerance=1e-14,
        phase_cap=32,kinetic_cap=64,output_cap=32,observe_every=n,snapshot_every=n)
    result=propagate(s;accuracy=tight,time=settings(.1,4))
    e=(1-cos(2pi/32))/K.spacing(p.grid)^2
    factor=((1-im*.1e/2)/(1+im*.1e/2))^4
    @test norm(dense(result.state)-factor*dense(s))<2e-10
    @test abs(last(result.observations).electron_number-1)<1e-11
    @test result.state.time≈.4
    # A spatially nonconstant Hamiltonian supplies a true splitting-error test.
    model=LocalPotential1D(x->.3cos(2pi*x/8);id="cosine-test")
    p=Problem(p.grid,model,[1.]);s=state_from_functions(p,[x->1+.2cos(2pi*x/8)];accuracy=tight)
    H=fd2(p)+Diagonal([model.potential(j*K.spacing(p.grid)) for j=0:31])
    exact=exp(-im*.4H)*dense(s)
    errors=Float64[]
    for (dt,n) in ((.1,4),(.05,8),(.025,16))
        r=propagate(s;accuracy=tight,time=settings(dt,n));push!(errors,norm(dense(r.state)-exact))
        @test abs(last(r.observations).electron_number-1)<1e-10
    end
    @test 3.7<errors[1]/errors[2]<4.3
    @test 3.7<errors[2]/errors[3]<4.3
    println("Time-step errors: ",errors)
    # No hidden normalization: initially non-unit amplitudes keep their charge.
    scaled=OrbitalState(p,[Q.scale(first(s.orbitals),.9)])
    r=propagate(scaled;accuracy=tight,time=settings(.02,2))
    @test last(r.observations).electron_number≈.81 atol=1e-10
    @test_throws ArgumentError propagate(s;time=TimeOptions(dt=0.))
end

