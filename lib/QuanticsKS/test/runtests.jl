@testset "Fixed H separates solved and occupied states" for (method,basis,nstates,wavevectors) in ((:block_residual,:projected,4,[-1,2]),(:block_residual,:direct,4,[-1,2]),(:block_green,:direct,5,[-1,2,-2]))
    p=Problem(PeriodicGrid1D(5,8),LocalPotential1D(x->.2cos(2pi*x/8);id="fixed-test"),[2.,2.])
    a=Accuracy(field_tolerance=1e-12,work_tolerance=1e-10,storage_tolerance=1e-12,algebra_tolerance=1e-13,orbital_cap=32,field_cap=32,work_cap=64,orthogonalization_tolerance=1e-12,green_rhs_tolerance=1e-12)
    state=state_from_functions(p,[x->1,x->cis(2pi*x/8)];accuracy=a)
    v=[p.model.potential(j*8/32) for j=0:31]
    # A fixed minimum budget checks all eigenpairs, including unoccupied orbitals.
    o=FixedSpectrumOptions(states=nstates,occupied_states=2,virtual_wavevectors=wavevectors,virtual_envelope_amplitude=.1,virtual_envelope_period=8.,min_iterations=40,max_iterations=60,energy_tolerance=1e-12,direction_residual_floor=1e-10,method=method,search_basis=basis)
    r=fixed_spectrum(state,v;spectrum=o,accuracy=a,solver=SCFOptions(green_polish_every=1))
    @test length(r.orbitals)==nstates
    @test length(r.occupied.orbitals)==2 && sum(r.occupied.problem.occupations)==4
    @test last(r.history).max_residual<first(r.history).max_residual/2
    @test last(r.history).trace<first(r.history).trace
    @test last(r.history).gram_defect<1e-8
    H=Matrix(Diagonal(16 .+v))
    for i=1:32;H[i,mod1(i+1,32)]=-8;H[i,mod1(i-1,32)]=-8;end
    reference=eigvals(Hermitian(H))[1:nstates]
    @test maximum(abs.(r.eigenvalues-reference))<1e-9
    @test r.converged
    @test_throws ArgumentError fixed_spectrum(state,v;spectrum=FixedSpectrumOptions(states=4,occupied_states=3,virtual_wavevectors=[-1]))
    if basis==:direct
        mktempdir() do dir
            cp=joinpath(dir,"spectrum.jls")
            hash=bytes2hex(K.sha256(reinterpret(UInt8,v)))
            K.spectrum_checkpoint(dir,p,r.orbitals,r.eigenvalues,r.history,o,hash)
            resumed=fixed_spectrum(state,v;spectrum=o,accuracy=a,resume_from=cp)
            @test resumed.converged && last(resumed.history).iteration>=o.min_iterations
            @test first(resumed.history).eigenvalues≈last(r.history).eigenvalues atol=1e-12
            @test_throws ArgumentError fixed_spectrum(state,v .+1e-6;spectrum=o,accuracy=a,resume_from=cp)
        end
    end
