function fd2(p)
    N=length(p.grid);h=K.spacing(p.grid)
    T=Matrix{ComplexF64}(I,N,N)/(p.mass*h^2)
    for j=1:N;T[j,mod1(j+1,N)]=-1/(2p.mass*h^2);T[j,mod1(j-1,N)]=-1/(2p.mass*h^2);end
    T
end

